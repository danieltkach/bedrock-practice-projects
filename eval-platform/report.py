"""Markdown report: ranking, recommendations, per-category winners, heatmap table, caveats."""
import json

import config
import recommend as rec_mod
import scoring

NARRATIVE_SYSTEM = (
    "You are the NARRATIVE WRITER of an LLM benchmark report. Write 120-180 words of plain prose (no bullet "
    "points, no headings) summarising the results for a technical reader. Use ONLY the numbers in the data you "
    "are given, never invent figures, and mention that the sample is small. Do not repeat the whole table.")


def label(name):
    return config.MODELS.get(name, {}).get("label", name)


def fmt_cost(x):
    return f"${x:.5f}" if x < 0.01 else f"${x:.4f}"


def table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def hardest_tests(records, n=5):
    """Tests with the lowest average quality across models (these separate or defeat the models)."""
    by_test = {}
    for r in records:
        q = scoring.quality_of(r)
        if q is not None:
            by_test.setdefault(r["test_id"], []).append(q)
    ranked = sorted(((scoring.mean(v), t) for t, v in by_test.items()))
    return [(t, q) for q, t in ranked[:n]]


def full_cost(records):
    """Estimated cost of ALL calls behind these results (test + judge calls), cache hits included."""
    total = 0.0
    for r in records:
        total += scoring.cost_of(r)
        for judge_name, j in ((r.get("judge") or {}).get("scores", {})).items():
            total += config.cost_usd(config.MODELS[judge_name]["id"], j.get("input_tokens", 0), j.get("output_tokens", 0))
    return total


def generate_narrative(llm, summary, recs):
    """Optional LLM-written paragraph (judge model). Clearly marked as generated in the report."""
    compact = {"weights": summary["weights"],
               "models": {label(n): {k: round(v, 4) for k, v in m.items() if isinstance(v, float)}
                          for n, m in summary["models"].items()},
               "recommendations": [{"title": r["title"], "model": label(r["model"])} for r in recs["recommendations"]]}
    result = llm.call(config.MODELS[config.JUDGE_MODEL]["id"], json.dumps(compact), system=NARRATIVE_SYSTEM,
                      max_tokens=600, temperature=0.2)
    return result.text if result.ok else ""


def build_report(records, meta, weights=None, narrative=None):
    summary = scoring.summarize(records, weights)
    recs = rec_mod.recommend(summary)
    winners = scoring.category_winners(summary)
    models = summary["models"]
    order = summary["ranking"]
    out = []

    out.append("# LLM Evaluation Report")
    out.append("")
    n_tests = len({r["test_id"] for r in records})
    judges = ", ".join(label(j) for j in meta.get("judges", [])) or "none"
    out.append(f"*Generated {meta.get('finished_at', 'n/a')}.* "
               f"**{len(models)} models**, **{len(summary['categories'])} categories**, **{n_tests} tests**, "
               f"**{len(records)} model calls**. Judge(s): **{judges}** (blind, temperature 0). "
               f"Estimated cost to reproduce all calls behind these results from scratch (test + judge): **${full_cost(records):.2f}**. "
               f"Estimated cash spent on this results folder, cumulative over resumed runs and cache hits excluded: **${meta.get('spent_usd', 0):.2f}**. "
               f"Prices in `config.py` are hand-typed ESTIMATES.")
    out.append("")
    w = summary["weights"]
    out.append(f"Aggregate score weights: quality {w['quality']:.2f}, cost {w['cost']:.2f}, latency {w['latency']:.2f}. "
               "**This is a single small sample (a few prompts per category): treat differences of a few points as noise.**")
    out.append("")

    out.append("## 1. Recommendations")
    out.append("")
    out.append("Generated by fixed rules from the data (see `recommend.py`); the *Rule* column says how each pick was made.")
    out.append("")
    out.append(table(["Recommendation", "Model", "Rule", "Evidence"],
                     [[r["title"], f"**{label(r['model'])}**", r["rule"], r["evidence"]] for r in recs["recommendations"]]))
    out.append("")
    if recs["warnings"]:
        out.append("**Warnings**")
        out.append("")
        out += [f"- {x}" for x in recs["warnings"]]
        out.append("")
    if narrative:
        out.append("> **LLM-generated narrative** (written by " + label(config.JUDGE_MODEL) +
                   " from the numbers above; verify it against the tables):")
        out.append(">")
        out += [f"> {line}" for line in narrative.splitlines()]
        out.append("")

    out.append("## 2. Overall ranking")
    out.append("")
    rows = []
    for i, n in enumerate(order, 1):
        m = models[n]
        rows.append([i, label(n), f"{m['aggregate']:.3f}", f"{m['quality']:.3f} (+/-{m['quality_ci']:.3f})",
                     fmt_cost(m["cost_per_call"]), f"{m['latency_median']:.2f}s", f"{m['latency_p95']:.2f}s",
                     f"{m['error_rate']:.0%}"])
    out.append(table(["#", "Model", "Aggregate", "Quality (95% interval)", "Cost / call", "Median latency", "p95 latency", "Failed calls"], rows))
    out.append("")
    out.append("Quality = mean over categories of the per-category mean (0 to 1). Cost / call = estimated USD for the "
               "test call only (judge calls excluded). Latency = seconds per call as measured when it was first made.")
    out.append("")

    out.append("## 3. Quality by category group")
    out.append("")
    groups = sorted({g for s in summary["group_scores"].values() for g in s})
    rows = [[label(n)] + [f"{summary['group_scores'][n].get(g, 0):.2f}" for g in groups] for n in order]
    out.append(table(["Model"] + groups, rows))
    out.append("")

    out.append("## 4. Category heatmap (quality 0-1, best per row in bold)")
    out.append("")
    rows = []
    for cat in summary["categories"]:
        scores = {n: summary["category_scores"][n].get(cat) for n in order}
        best = max((v for v in scores.values() if v is not None), default=None)
        cells = []
        for n in order:
            v = scores[n]
            cells.append("-" if v is None else (f"**{v:.2f}**" if v == best else f"{v:.2f}"))
        rows.append([cat] + cells)
    out.append(table(["Category"] + [label(n) for n in order], rows))
    out.append("")

    out.append("## 5. Per-category winners")
    out.append("")
    out.append(f"Highest quality wins; models within {config.CATEGORY_TIE_MARGIN} of the best are tied and the cheaper one is named.")
    out.append("")
    rows = []
    for cat, win in winners.items():
        n_tied = len(win["tied"])
        name = label(win["winner"]) + (f" (tie of {n_tied})" if n_tied > 1 else "")
        others = ", ".join(label(t) for t in win["tied"] if t != win["winner"]) if 1 < n_tied <= 3 else (f"{n_tied - 1} other models" if n_tied > 3 else "-")
        rows.append([cat, name, f"{win['quality']:.2f}", others])
    out.append(table(["Category", "Winner", "Quality", "Tied with"], rows))
    out.append("")

    out.append("## 6. Hardest tests")
    out.append("")
    out.append("Lowest average quality across all models. Read the responses in the dashboard to see whether the model or the test is at fault.")
    out.append("")
    out.append(table(["Test", "Mean quality"], [[t, f"{q:.2f}"] for t, q in hardest_tests(records)]))
    out.append("")

    agreement = scoring.judge_agreement(records)
    if agreement:
        a, b = agreement["judges"]
        out.append("## 7. Judge agreement")
        out.append("")
        out.append(f"{agreement['n']} answers were scored by both judges ({label(a)} and {label(b)}). "
                   f"They gave the identical score {agreement['exact']:.0%} of the time; the mean absolute difference was "
                   f"{agreement['mean_abs_diff']:.2f} points on the 1-5 scale. Mean score given: {label(a)} "
                   f"{agreement['mean_scores'][a]:.2f}, {label(b)} {agreement['mean_scores'][b]:.2f}. "
                   "A model is never judged by itself when another judge exists, so the two judges' views are combined only for the other models.")
        out.append("")
    out.append("## 8. Method and caveats" if agreement else "## 7. Method and caveats")
    out.append("")
    out.append(f"- **Quality** of one answer = {config.AUTO_WEIGHT:.0%} automatic checks + {1 - config.AUTO_WEIGHT:.0%} judge score "
               "when a test has both; otherwise whichever exists. Judge scores 1-5 are mapped to 0-1.")
    out.append("- **Judge bias:** LLM judges favour their own style and longer answers. Here the judge is blind to the author, "
               "uses a rubric at temperature 0, and a model is not judged by itself when a second judge is configured. "
               "A judge that is also a competitor is still a limitation.")
    out.append("- **Latency** depends on load, region and time of day; each call was measured once.")
    out.append("- **Cost** uses estimated list prices and the real token counts returned by the API.")
    out.append("- **Sample size:** a few prompts per category means wide uncertainty (see the quality intervals). "
               "Use this as a methodology demo and a first filter, not a final verdict.")
    out.append("- BLEU/ROUGE/BERTScore are not used: they measure overlap with one reference text, which punishes valid "
               "paraphrases and suits summarization/translation benchmarks with many references; a rubric judge plus "
               "executable checks fits open-ended answers better.")
    out.append("")
    return "\n".join(out)
